import OGame
import XCTest

final class AutomatedTransportLinesTests: XCTestCase {

    private let sut = AutomatedTransportLines()

    func testId() throws {
        XCTAssertEqual(sut.id, 13_206)
    }

    func testName() throws {
        XCTAssertEqual(sut.name, "Automated Transport Lines")
    }

    func testLifeform() throws {
        XCTAssertEqual(sut.lifeform, .mechas)
    }

    func testBaseCost() throws {
        XCTAssertEqual(sut.baseCost, Resources(metal: 50_000, crystal: 50_000, deuterium: 20_000))
    }

    func testIncreaseFactors() throws {
        XCTAssertEqual(sut.costIncreaseFactor, 1.50)
    }

    func testDuration() throws {
        XCTAssertEqual(sut.baseDuration, 5_000)
        XCTAssertEqual(sut.durationFactor, 1.3)
    }

    func testRequirements() throws {
        XCTAssertEqual(sut.requirements, [])
    }
}
