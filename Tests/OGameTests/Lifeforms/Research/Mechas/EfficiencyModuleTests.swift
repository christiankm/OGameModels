import OGame
import XCTest

final class EfficiencyModuleTests: XCTestCase {

    private let sut = EfficiencyModule()

    func testId() throws {
        XCTAssertEqual(sut.id, 13_203)
    }

    func testName() throws {
        XCTAssertEqual(sut.name, "Efficiency Module")
    }

    func testLifeform() throws {
        XCTAssertEqual(sut.lifeform, .mechas)
    }

    func testBaseCost() throws {
        XCTAssertEqual(sut.baseCost, Resources(metal: 15_000, crystal: 10_000, deuterium: 5_000))
    }

    func testIncreaseFactors() throws {
        XCTAssertEqual(sut.costIncreaseFactor, 1.50)
    }

    func testDuration() throws {
        XCTAssertEqual(sut.baseDuration, 2_500)
        XCTAssertEqual(sut.durationFactor, 1.4)
    }

    func testRequirements() throws {
        XCTAssertEqual(sut.requirements, [])
    }
}
