import OGame
import XCTest

final class GeneralOverhaulDestroyerTests: XCTestCase {

    private let sut = GeneralOverhaulDestroyer()

    func testId() throws {
        XCTAssertEqual(sut.id, 13_216)
    }

    func testName() throws {
        XCTAssertEqual(sut.name, "General Overhaul Destroyer")
    }

    func testLifeform() throws {
        XCTAssertEqual(sut.lifeform, .mechas)
    }

    func testBaseCost() throws {
        XCTAssertEqual(sut.baseCost, Resources(metal: 320_000, crystal: 240_000, deuterium: 100_000))
    }

    func testIncreaseFactors() throws {
        XCTAssertEqual(sut.costIncreaseFactor, 1.50)
    }

    func testDuration() throws {
        XCTAssertEqual(sut.baseDuration, 10_000)
        XCTAssertEqual(sut.durationFactor, 1.4)
    }

    func testRequirements() throws {
        XCTAssertEqual(sut.requirements, [])
    }
}
