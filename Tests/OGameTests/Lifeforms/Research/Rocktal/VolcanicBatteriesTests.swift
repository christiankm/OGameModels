import OGame
import XCTest

final class VolcanicBatteriesTests: XCTestCase {

    private let sut = VolcanicBatteries()

    func testId() throws {
        XCTAssertEqual(sut.id, 12_201)
    }

    func testName() throws {
        XCTAssertEqual(sut.name, "Volcanic Batteries")
    }

    func testLifeform() throws {
        XCTAssertEqual(sut.lifeform, .rocktal)
    }

    func testBaseCost() throws {
        XCTAssertEqual(sut.baseCost, Resources(metal: 10_000, crystal: 6_000, deuterium: 1_000))
    }

    func testIncreaseFactors() throws {
        XCTAssertEqual(sut.costIncreaseFactor, 1.50)
    }

    func testDuration() throws {
        XCTAssertEqual(sut.baseDuration, 1_000)
        XCTAssertEqual(sut.durationFactor, 1.3)
    }

    func testRequirements() throws {
        XCTAssertEqual(sut.requirements, [])
    }
}
