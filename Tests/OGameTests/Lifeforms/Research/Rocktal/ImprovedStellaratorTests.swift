import OGame
import XCTest

final class ImprovedStellaratorTests: XCTestCase {

    private let sut = ImprovedStellarator()

    func testId() throws {
        XCTAssertEqual(sut.id, 12_209)
    }

    func testName() throws {
        XCTAssertEqual(sut.name, "Improved Stellarator")
    }

    func testLifeform() throws {
        XCTAssertEqual(sut.lifeform, .rocktal)
    }

    func testBaseCost() throws {
        XCTAssertEqual(sut.baseCost, Resources(metal: 75_000, crystal: 55_000, deuterium: 25_000))
    }

    func testIncreaseFactors() throws {
        XCTAssertEqual(sut.costIncreaseFactor, 1.50)
    }

    func testDuration() throws {
        XCTAssertEqual(sut.baseDuration, 6_500)
        XCTAssertEqual(sut.durationFactor, 1.3)
    }

    func testRequirements() throws {
        XCTAssertEqual(sut.requirements, [])
    }
}
