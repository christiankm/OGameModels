import OGame
import XCTest

final class HighPerformanceExtractorsTests: XCTestCase {

    private let sut = HighPerformanceExtractors()

    func testId() throws {
        XCTAssertEqual(sut.id, 11_202)
    }

    func testName() throws {
        XCTAssertEqual(sut.name, "High Performance Extractors")
    }

    func testLifeform() throws {
        XCTAssertEqual(sut.lifeform, .humans)
    }

    func testBaseCost() throws {
        XCTAssertEqual(sut.baseCost, Resources(metal: 7_000, crystal: 10_000, deuterium: 5_000))
    }

    func testIncreaseFactors() throws {
        XCTAssertEqual(sut.costIncreaseFactor, 1.50)
    }

    func testDuration() throws {
        XCTAssertEqual(sut.baseDuration, 2_000)
        XCTAssertEqual(sut.durationFactor, 1.3)
    }

    func testRequirements() throws {
        XCTAssertEqual(sut.requirements, [])
    }
}
