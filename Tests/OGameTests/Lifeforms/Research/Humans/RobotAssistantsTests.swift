import OGame
import XCTest

final class RobotAssistantsTests: XCTestCase {

    private let sut = RobotAssistants()

    func testId() throws {
        XCTAssertEqual(sut.id, 11_217)
    }

    func testName() throws {
        XCTAssertEqual(sut.name, "Robot Assistants")
    }

    func testLifeform() throws {
        XCTAssertEqual(sut.lifeform, .humans)
    }

    func testBaseCost() throws {
        XCTAssertEqual(sut.baseCost, Resources(metal: 300_000, crystal: 180_000, deuterium: 120_000))
    }

    func testIncreaseFactors() throws {
        XCTAssertEqual(sut.costIncreaseFactor, 1.50)
    }

    func testDuration() throws {
        XCTAssertEqual(sut.baseDuration, 11_000)
        XCTAssertEqual(sut.durationFactor, 1.3)
    }

    func testRequirements() throws {
        XCTAssertEqual(sut.requirements, [])
    }
}
