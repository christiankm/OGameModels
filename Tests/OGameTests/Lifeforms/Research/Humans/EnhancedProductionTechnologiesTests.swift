import OGame
import XCTest

final class EnhancedProductionTechnologiesTests: XCTestCase {

    private let sut = EnhancedProductionTechnologies()

    func testId() throws {
        XCTAssertEqual(sut.id, 11_208)
    }

    func testName() throws {
        XCTAssertEqual(sut.name, "Enhanced Production Technologies")
    }

    func testLifeform() throws {
        XCTAssertEqual(sut.lifeform, .humans)
    }

    func testBaseCost() throws {
        XCTAssertEqual(sut.baseCost, Resources(metal: 80_000, crystal: 50_000, deuterium: 20_000))
    }

    func testIncreaseFactors() throws {
        XCTAssertEqual(sut.costIncreaseFactor, 1.50)
    }

    func testDuration() throws {
        XCTAssertEqual(sut.baseDuration, 6_000)
        XCTAssertEqual(sut.durationFactor, 1.3)
    }

    func testRequirements() throws {
        XCTAssertEqual(sut.requirements, [])
    }
}
