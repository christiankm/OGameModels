import OGame
import XCTest

final class EfficientSwarmIntelligenceTests: XCTestCase {

    private let sut = EfficientSwarmIntelligence()

    func testId() throws {
        XCTAssertEqual(sut.id, 14_213)
    }

    func testName() throws {
        XCTAssertEqual(sut.name, "Efficient Swarm Intelligence")
    }

    func testLifeform() throws {
        XCTAssertEqual(sut.lifeform, .kaelesh)
    }

    func testBaseCost() throws {
        XCTAssertEqual(sut.baseCost, Resources(metal: 200_000, crystal: 100_000, deuterium: 100_000))
    }

    func testIncreaseFactors() throws {
        XCTAssertEqual(sut.costIncreaseFactor, 1.50)
    }

    func testDuration() throws {
        XCTAssertEqual(sut.baseDuration, 8_500)
        XCTAssertEqual(sut.durationFactor, 1.3)
    }

    func testRequirements() throws {
        XCTAssertEqual(sut.requirements, [])
    }
}
