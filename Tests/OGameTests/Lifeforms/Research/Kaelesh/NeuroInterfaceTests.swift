import OGame
import XCTest

final class NeuroInterfaceTests: XCTestCase {

    private let sut = NeuroInterface()

    func testId() throws {
        XCTAssertEqual(sut.id, 14_207)
    }

    func testName() throws {
        XCTAssertEqual(sut.name, "Neuro Interface")
    }

    func testLifeform() throws {
        XCTAssertEqual(sut.lifeform, .kaelesh)
    }

    func testBaseCost() throws {
        XCTAssertEqual(sut.baseCost, Resources(metal: 70_000, crystal: 40_000, deuterium: 20_000))
    }

    func testIncreaseFactors() throws {
        XCTAssertEqual(sut.costIncreaseFactor, 1.50)
    }

    func testDuration() throws {
        XCTAssertEqual(sut.baseDuration, 5_500)
        XCTAssertEqual(sut.durationFactor, 1.3)
    }

    func testRequirements() throws {
        XCTAssertEqual(sut.requirements, [])
    }
}
