import OGame
import XCTest

final class GravitationSensorsTests: XCTestCase {

    private let sut = GravitationSensors()

    func testId() throws {
        XCTAssertEqual(sut.id, 14_215)
    }

    func testName() throws {
        XCTAssertEqual(sut.name, "Gravitation Sensors")
    }

    func testLifeform() throws {
        XCTAssertEqual(sut.lifeform, .kaelesh)
    }

    func testBaseCost() throws {
        XCTAssertEqual(sut.baseCost, Resources(metal: 240_000, crystal: 120_000, deuterium: 120_000))
    }

    func testIncreaseFactors() throws {
        XCTAssertEqual(sut.costIncreaseFactor, 1.50)
    }

    func testDuration() throws {
        XCTAssertEqual(sut.baseDuration, 9_500)
        XCTAssertEqual(sut.durationFactor, 1.4)
    }

    func testRequirements() throws {
        XCTAssertEqual(sut.requirements, [])
    }
}
